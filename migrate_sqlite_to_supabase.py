#!/usr/bin/env python3
"""One-time import of the existing TRADEIN SQLite database into Supabase PostgreSQL."""
import os, sqlite3, sys
import psycopg

SQL = """
CREATE TABLE IF NOT EXISTS trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket TEXT, symbol TEXT NOT NULL, direction TEXT NOT NULL,
    open_time TEXT, close_time TEXT, entry DOUBLE PRECISION, exit DOUBLE PRECISION,
    volume DOUBLE PRECISION, sl DOUBLE PRECISION, tp DOUBLE PRECISION,
    pnl DOUBLE PRECISION NOT NULL DEFAULT 0,
    commission DOUBLE PRECISION DEFAULT 0, swap DOUBLE PRECISION DEFAULT 0,
    strategy TEXT, session TEXT, setup TEXT, emotion TEXT,
    followed_plan INTEGER DEFAULT 1, notes TEXT, screenshot TEXT,
    reason_entry TEXT, reason_exit TEXT, decision_making TEXT, outcome_decision TEXT,
    confluences TEXT, lessons TEXT, created_at TEXT
)
"""

def main():
    db_path = sys.argv[1] if len(sys.argv) > 1 else "trades.db"
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        raise SystemExit("Set DATABASE_URL to your Supabase PostgreSQL connection string first.")
    if not os.path.isfile(db_path):
        raise SystemExit(f"SQLite file not found: {db_path}")
    src = sqlite3.connect(db_path)
    src.row_factory = sqlite3.Row
    rows = src.execute("SELECT * FROM trades ORDER BY id").fetchall()
    if not rows:
        raise SystemExit("SQLite database contains no trades; nothing imported.")
    cols = [r[1] for r in src.execute("PRAGMA table_info(trades)").fetchall()]
    # Target schema is kept aligned with the TRADEIN app. Include only columns present in source.
    with psycopg.connect(url) as dst:
        dst.execute(SQL)
        target_cols = [r[0] for r in dst.execute(
            "SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name='trades'"
        ).fetchall()]
        use_cols = [c for c in cols if c in target_cols]
        placeholders = ",".join(["%s"] * len(use_cols))
        col_sql = ",".join(f'"{c}"' for c in use_cols)
        updates = ",".join(f'"{c}"=EXCLUDED."{c}"' for c in use_cols if c != "id")
        query = f"INSERT INTO trades ({col_sql}) VALUES ({placeholders}) ON CONFLICT (id) DO UPDATE SET {updates}"
        for row in rows:
            dst.execute(query, [row[c] for c in use_cols])
        dst.execute("""
            SELECT setval(pg_get_serial_sequence('public.trades','id'),
                          GREATEST(COALESCE((SELECT MAX(id) FROM public.trades), 1), 1),
                          EXISTS(SELECT 1 FROM public.trades))
        """)
        count = dst.execute("SELECT COUNT(*) FROM trades").fetchone()[0]
    print(f"Imported/upserted {len(rows)} SQLite rows. PostgreSQL now contains {count} trade rows.")
    print("IDs and all available trade/review fields were preserved.")
    src.close()

if __name__ == "__main__":
    main()
